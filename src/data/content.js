<p>为更好引导冰柿产业创新升级，保定市强化顶层设计，出台《保定市柿子产业高质量发展三年行动计划（ 2024 — 2026 年）》《保定冰柿品牌培育推广营销方案》，启动系列规范性标准制定工作，做大做强保定冰柿品牌。此外，组织龙头企业、合作社、种植大户等约 30 家经营主体成立保定市柿子产业高质量发展联盟，充分发挥各经营主体优势，引导柿子产业联合发展。</p>
